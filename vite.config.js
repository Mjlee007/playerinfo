import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";
import { createHash } from "node:crypto";

// Generates dist/sw.js at build time with the full list of built files,
// so the whole app is cached on first visit and then works without internet.
function offlineServiceWorker() {
  let base = "/";
  return {
    name: "offline-service-worker",
    apply: "build",
    configResolved(config) {
      base = config.base;
    },
    generateBundle(_, bundle) {
      const files = Object.keys(bundle).filter((f) => !f.endsWith(".map"));
      const urls = [base, ...files.map((f) => base + f), base + "manifest.webmanifest", base + "icon.svg"];
      const version = createHash("sha1").update(files.sort().join("|")).digest("hex").slice(0, 10);
      this.emitFile({ type: "asset", fileName: "sw.js", source: swSource(version, base, urls) });
    },
  };
}

const swSource = (version, base, urls) => `// Generated by vite.config.js — do not edit.
const APP_CACHE = "playerinfo-app-${version}";
const FONT_CACHE = "playerinfo-fonts-v1";
const INDEX = ${JSON.stringify(base)};
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(APP_CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== APP_CACHE && k !== FONT_CACHE && k !== "playerinfo-models").map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);

  // Page loads (any route, e.g. /players/3): try the network for the newest version, else the cached app.
  if (req.mode === "navigate") {
    event.respondWith(
      fetch(req)
        .then((res) => {
          if (res.ok) caches.open(APP_CACHE).then((c) => c.put(INDEX, res.clone()));
          return res;
        })
        .catch(() => caches.match(INDEX))
    );
    return;
  }

  // Google Fonts: serve from cache, refresh in the background when online.
  if (url.hostname === "fonts.googleapis.com" || url.hostname === "fonts.gstatic.com") {
    event.respondWith(
      caches.open(FONT_CACHE).then(async (cache) => {
        const cached = await cache.match(req);
        const network = fetch(req)
          .then((res) => {
            if (res.ok || res.type === "opaque") cache.put(req, res.clone());
            return res;
          })
          .catch(() => cached);
        return cached || network;
      })
    );
    return;
  }

  // App files (hashed JS/CSS, icons): cache first, then network.
  if (url.origin === self.location.origin) {
    event.respondWith(
      caches.match(req).then(
        (cached) =>
          cached ||
          fetch(req).then((res) => {
            if (res.ok) caches.open(APP_CACHE).then((c) => c.put(req, res.clone()));
            return res;
          })
      )
    );
  }
});
`;

export default defineConfig({
  plugins: [react(), offlineServiceWorker()],
  server: { open: true },
});
